// CTAP response tokens are compiled on the host; runtime uses only fixed bytes.
use minicbor::{Encoder, encode::Error};
use std::{convert::Infallible, fmt::Write};
type E = Encoder<Vec<u8>>;
type R = Result<(), Error<Infallible>>;
fn fragment(out: &mut String, name: &str, encode: impl FnOnce(&mut E) -> R) {
    let mut e = E::new(Vec::new());
    encode(&mut e).unwrap();
    write!(out, "pub const {name}: &[u8] = &[").unwrap();
    for byte in e.writer() {
        write!(out, "0x{byte:02x},").unwrap();
    }
    writeln!(out, "];").unwrap();
}
fn main() {
    let mut out = String::from("// Generated by canokey-ctap/build.rs; do not edit.\n");
    // Keep invariant response fields out of the device's encoding call graph.
    fragment(&mut out, "MAKE_HEADER", |e| {
        e.map(3)?.u8(1)?.str("packed")?.u8(2)?;
        Ok(())
    });
    fragment(&mut out, "SELF_ATTESTATION", |e| {
        e.map(2)?.str("alg")?;
        Ok(())
    });
    fragment(&mut out, "ATTESTATION", |e| {
        e.map(3)?.str("alg")?.i8(-7)?.str("sig")?;
        Ok(())
    });
    fragment(&mut out, "CERTIFICATE", |e| {
        e.str("x5c")?.array(1)?;
        Ok(())
    });
    fragment(&mut out, "DESCRIPTOR", |e| {
        e.map(2)?.str("id")?;
        Ok(())
    });
    fragment(&mut out, "PUBLIC_KEY_TYPE", |e| {
        e.str("type")?.str("public-key")?;
        Ok(())
    });
    for (name, value) in [
        ("USER_ID", "id"),
        ("USER_NAME", "name"),
        ("USER_DISPLAY", "displayName"),
    ] {
        fragment(&mut out, name, |e| {
            e.str(value)?;
            Ok(())
        });
    }
    for (name, kind, algorithm) in [
        ("COSE_ED25519", 1, -8),
        ("COSE_MLDSA65", 7, canokey_ports::mldsa::DSA65.cose),
        ("COSE_MLDSA44", 7, canokey_ports::mldsa::DSA44.cose),
    ] {
        fragment(&mut out, name, |e| {
            e.map(if kind == 7 { 3 } else { 4 })?
                .u8(1)?
                .u8(kind)?
                .u8(3)?
                .i32(algorithm)?
                .i8(-1)?;
            // AKP carries the public key directly at -1, without an OKP curve.
            if kind != 7 {
                e.u8(6)?.i8(-2)?;
            }
            Ok(())
        });
    }
    fragment(&mut out, "COSE_EC2", |e| {
        e.map(5)?.u8(1)?.u8(2)?.u8(3)?;
        Ok(())
    });
    let path = std::path::PathBuf::from(std::env::var_os("OUT_DIR").unwrap());
    std::fs::write(path.join("ctap_response.rs"), out).unwrap();
}
