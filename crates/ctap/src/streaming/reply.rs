//! Bounded framing plans; generated public keys remain owned by the stream.
use super::{MATERIAL_BYTES, Mode, Pending};
use crate::response::{
    auth_data,
    credential::{self as reply, Body, Fields},
};
use crate::signing::DIGEST_BYTES;
use canokey_ports::mldsa::SEED_BYTES;

// The largest supported ML-DSA COSE prefix fits this existing local buffer.
const COSE_PREFIX_BYTES: usize = 32;
use crate::{
    credential, resident,
    response::encoding::{self, EncodeError, Encoder},
};

/// Encode from the borrowed resident record before its input storage is reused
/// for the stream seed. The returned length excludes the generated public key;
/// callers stage the seed and publish the plan only after successful encoding.
#[inline(always)]
pub fn public(
    entry: &resident::Entry<'_>,
    algorithm: u8,
    id: &credential::Id,
    total: Option<u8>,
    blob_key: Option<&[u8; credential::KEY_BYTES]>,
    output: &mut [u8],
) -> Result<(Pending, usize), EncodeError> {
    let capacity = output.len();
    let (status, body) = output.split_first_mut().ok_or(EncodeError)?;
    *status = 0x00;
    let mut encoder = Encoder::new(body);
    encoding::management_header(&mut encoder, entry, total.is_some(), blob_key.is_some())?;
    encoder.u8(encoding::management::PUBLIC_KEY).finish()?;
    encoding::mldsa_public_header(&mut encoder, algorithm)?;
    let public_at = capacity - encoder.writer().len();
    encoding::management_tail(&mut encoder, id, total, blob_key.map(|key| &key[..]))?;
    let length = capacity - encoder.writer().len();
    Ok((
        Pending {
            algorithm,
            mode: Mode::Public,
            prefix: public_at,
            auth: 0,
            public_at,
            signature_at: 0,
            certificate: None,
            output: length,
            hash_prefix: (0, 0),
            hash_suffix: (0, 0),
        },
        length,
    ))
}

/// Request metadata contains only loans and scalars; private seed and resident
/// record storage remain in the existing workspace throughout construction.
pub struct CredentialFields<'a> {
    pub id: &'a credential::Id,
    pub client_hash: &'a [u8; crate::signing::DIGEST_BYTES],
    pub algorithm: u8,
    pub count: u8,
    pub details: bool,
    pub blob_key: bool,
}
/// Existing admitted internal views: input includes room for authData and the
/// hash/seed staging pair; output admits fixed authData/COSE copies before the
/// fallible tail encoder runs. Products validate these capacities, not wire data.
pub struct Buffers<'a> {
    pub key: &'a mut [u8],
    pub input: &'a mut [u8],
    pub output: &'a mut [u8],
}
/// Static projections keep workspace and platform loans separate across the
/// outlined certificate/extension/user stages. Implementations retain no loans
/// and provide required (nonempty, bounded) certificate admission, never the
/// ordinary self-attestation fallback. Errors leave publication to the owner.
pub trait Construction {
    type Request: ?Sized;
    type Workspace: ?Sized;
    type Platform: ?Sized;
    type Error;
    fn invalid() -> Self::Error;
    fn fields(request: &Self::Request) -> CredentialFields<'_>;
    fn buffers(workspace: &mut Self::Workspace) -> Buffers<'_>;
    fn certificate(platform: &mut Self::Platform) -> Result<usize, Self::Error>;
    fn extensions(
        platform: &mut Self::Platform,
        request: &Self::Request,
        workspace: &mut Self::Workspace,
        cursor: usize,
    ) -> Result<usize, Self::Error>;
    fn user<'a>(
        request: &Self::Request,
        key: &'a mut [u8],
        platform: &mut Self::Platform,
    ) -> Result<Option<resident::Entry<'a>>, Self::Error>;
    fn blob_key(
        request: &Self::Request,
        output: &mut [u8; credential::KEY_BYTES],
        platform: &mut Self::Platform,
    ) -> Result<(), Self::Error>;
    fn wipe(platform: &Self::Platform, bytes: &mut [u8]);
    fn attested(output: &mut [u8], id: &credential::Id);
}

/// Construct framing over admitted internal workspace offsets. The owner stages
/// and publishes the returned plan only on success; generated bytes stay external.
#[inline(always)]
pub fn assertion<C: Construction>(
    platform: &mut C::Platform,
    request: &C::Request,
    workspace: &mut C::Workspace,
    auth_len: usize,
) -> Result<(Pending, usize), C::Error> {
    let fields = C::fields(request);
    let params = canokey_ports::mldsa::parameters(fields.algorithm).ok_or_else(C::invalid)?;
    let Buffers { key, input, output } = C::buffers(workspace);
    let capacity = output.len();
    let has_blob_key = fields.blob_key;
    input[auth_len..auth_len + DIGEST_BYTES].copy_from_slice(fields.client_hash);
    input[auth_len + DIGEST_BYTES..auth_len + MATERIAL_BYTES].copy_from_slice(&key[..SEED_BYTES]);
    // The resident record replaces the key backing. Stage the seed first so
    // user encoding cannot change the material subsequently consumed by Stream.
    let user = C::user(request, key, platform)?;
    output[0] = 0x00;
    let mut e = Encoder::new(&mut output[1..]);
    reply::start_fields(
        &mut e,
        Fields {
            make: false,
            user: user.is_some(),
            count: fields.count,
            blob_key: has_blob_key,
        },
        fields.id,
        Body::External(auth_len),
    )
    .map_err(|_| C::invalid())?;
    e.finish().map_err(|_| C::invalid())?;
    let prefix = capacity - e.writer().len();
    let mut tail = Encoder::new(&mut output[prefix..]);
    let signature_at = capacity - reply::signature_header(&mut tail, params.signature_bytes);
    reply::tail_fields(&mut tail, user.is_some(), fields.count, |e| {
        encoding::user(e, user.as_ref().unwrap(), fields.details)
    })
    .map_err(|_| C::invalid())?;
    if has_blob_key {
        let mut key = [0x00; credential::KEY_BYTES];
        C::blob_key(request, &mut key, platform)?;
        reply::blob_key(&mut tail, false, &key);
        C::wipe(platform, &mut key);
    }
    tail.finish().map_err(|_| C::invalid())?;
    let output = capacity - tail.writer().len();
    let plan = Pending {
        algorithm: fields.algorithm,
        mode: Mode::Assert,
        prefix,
        auth: auth_len,
        public_at: 0,
        // The generated signature follows the key-3 byte-string header.  `prefix`
        // points at the start of that header, so inserting at it would place the
        // signature before its own CBOR length prefix.
        signature_at,
        certificate: None,
        output,
        hash_prefix: (prefix, auth_len),
        hash_suffix: (prefix, auth_len),
    };
    Ok((plan, output + auth_len + params.signature_bytes))
}

/// Construct framing over admitted internal workspace offsets. The owner stages
/// and publishes the returned plan only on success; generated bytes stay external.
#[inline(always)]
pub fn make<C: Construction>(
    platform: &mut C::Platform,
    request: &C::Request,
    workspace: &mut C::Workspace,
    auth_prefix: usize,
) -> Result<(Pending, usize), C::Error> {
    let fields = C::fields(request);
    let params = canokey_ports::mldsa::parameters(fields.algorithm).ok_or_else(C::invalid)?;
    let cert_len = C::certificate(platform)?;
    // Extensions are encoded once for classic and streamed keys. The large
    // public key is spliced between the COSE header and these extension bytes.
    let auth_end = C::extensions(platform, request, workspace, auth_prefix)?;
    let Buffers { key, input, output } = C::buffers(workspace);
    let capacity = output.len();
    let extension_len = auth_end - auth_prefix;
    let mut cose = [0x00; COSE_PREFIX_BYTES];
    let mut ce = Encoder::new(&mut cose[..]);
    encoding::mldsa_public_header(&mut ce, fields.algorithm).map_err(|_| C::invalid())?;
    let cose_prefix_len = COSE_PREFIX_BYTES - ce.writer().len();
    let auth_prefix_len = auth_data::CREDENTIAL_OFFSET + credential::ID_BYTES + cose_prefix_len;
    let has_blob_key = fields.blob_key;
    output[0] = 0x00;
    let mut e = Encoder::new(&mut output[1..]);
    reply::start_fields(
        &mut e,
        Fields {
            make: true,
            user: false,
            count: 0,
            blob_key: has_blob_key,
        },
        fields.id,
        Body::External(auth_prefix_len + params.public_bytes + extension_len),
    )
    .map_err(|_| C::invalid())?;
    e.finish().map_err(|_| C::invalid())?;
    let auth_start = capacity - e.writer().len();
    output[auth_start..auth_start + auth_prefix].copy_from_slice(&input[..auth_prefix]);
    C::attested(&mut output[auth_start..], fields.id);
    let cose_at = auth_start + auth_data::CREDENTIAL_OFFSET + credential::ID_BYTES;
    let public_at = cose_at + cose_prefix_len;
    output[cose_at..public_at].copy_from_slice(&cose[..cose_prefix_len]);
    output[public_at..public_at + extension_len].copy_from_slice(&input[auth_prefix..auth_end]);
    let mut tail = Encoder::new(&mut output[public_at + extension_len..]);
    reply::statement_prefix(&mut tail, true, None).map_err(|_| C::invalid())?;
    tail.finish().map_err(|_| C::invalid())?;
    // Stream::attest inserts the encoded DER signature here, exactly once.
    let signature_at = capacity - tail.writer().len();
    reply::certificate_body(&mut tail, Body::External(cert_len));
    tail.finish().map_err(|_| C::invalid())?;
    let cert_at = capacity - tail.writer().len();
    if has_blob_key {
        let mut key = [0x00; credential::KEY_BYTES];
        C::blob_key(request, &mut key, platform)?;
        reply::blob_key(&mut tail, true, &key);
        C::wipe(platform, &mut key);
    }
    tail.finish().map_err(|_| C::invalid())?;
    let output = capacity - tail.writer().len();
    // Registration staging is the final mutation before returning a plan. All
    // fallible material/extension/framing operations must succeed first.
    input[..DIGEST_BYTES].copy_from_slice(fields.client_hash);
    input[DIGEST_BYTES..MATERIAL_BYTES].copy_from_slice(&key[..SEED_BYTES]);
    let plan = Pending {
        algorithm: fields.algorithm,
        mode: Mode::Make,
        prefix: auth_start,
        auth: 0,
        public_at,
        signature_at,
        certificate: Some((cert_at, cert_len)),
        output,
        hash_prefix: (auth_start, auth_prefix_len),
        hash_suffix: (public_at, extension_len),
    };
    Ok((plan, output + params.public_bytes + cert_len))
}
